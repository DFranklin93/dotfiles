vim.cmd("set number") -- line numbers
vim.cmd("set relativenumber") -- relative line numbers
vim.cmd("set cursorline") -- highlight current line
vim.cmd("set scrolloff=10") -- keep 10 lines above/below cursor

vim.cmd("set expandtab") -- use spaces instead of tabs
vim.cmd("set tabstop=2") -- tab width
vim.cmd("set softtabstop=2") -- soft tab stop not tabs on tab/backspace
vim.cmd("set shiftwidth=2") -- indent width
